/* Deterministic advanced question banks.  No network or random state is used. */

const asText = (value) => String(value);

function choices(correct, distractors, answer = 0) {
  const values = [correct, ...distractors.slice(0, 3)].map(asText);
  if (values.length !== 4 || new Set(values).size !== 4) {
    throw new Error(
      `Each question must provide four distinct options: ${values.join(" | ")}`,
    );
  }
  const front = values[0];
  const rest = values.slice(1, 4);
  const index = Math.max(0, Math.min(3, answer));
  rest.splice(index, 0, front);
  return { options: rest, answer: index };
}

function question(
  id,
  prompt,
  correct,
  distractors,
  explanation,
  difficulty,
  answer = 0,
) {
  const selected = choices(correct, distractors, answer);
  return {
    id,
    prompt,
    options: selected.options,
    answer: selected.answer,
    explanation,
    difficulty,
  };
}

function rebalance(pool) {
  return pool.map((item, index) => {
    const correct = item.options[item.answer];
    const distractors = item.options.filter(
      (_, optionIndex) => optionIndex !== item.answer,
    );
    const selected = choices(correct, distractors, index % 4);
    return { ...item, options: selected.options, answer: selected.answer };
  });
}

