function shortReadingPool(records, prefix) {
  const pool = [];
  records.forEach((record, recordIndex) => {
    const [topic, passage, claim, inference, titleDistractor, wrong] = record;
    const targets = [
      claim,
      inference,
      `${topic}에서 조건과 결과 살피기`,
      claim,
    ];
    const stems = [
      "글의 중심 주장으로 가장 적절한 것은?",
      "글에서 추론할 수 있는 것은?",
      "이 글의 제목으로 가장 적절한 것은?",
      "글의 사례가 뒷받침하는 판단은?",
    ];
    for (let variant = 0; variant < 4; variant++) {
      const correct = targets[variant];
      const overreach = `${inference.replace(/다$/, "다는")} 사실만으로 다른 조건에서도 같은 결과가 반드시 보장된다`;
      const distractors = [wrong, titleDistractor, overreach];
      pool.push(
        question(
          `${prefix}-reading-${String(recordIndex * 4 + variant + 1).padStart(2, "0")}`,
          `${passage}\n\n${stems[variant]}`,
          correct,
          distractors,
          variant === 0
            ? `사례의 관찰과 조치가 함께 보여 주는 핵심은 “${claim}”이다.`
            : `본문의 조건과 결과를 연결하면 “${correct}”라는 판단만 직접 뒷받침된다.`,
          ((recordIndex + variant) % 3) + 1,
          variant,
        ),
      );
    }
  });
  return pool;
}

