function longReadingPool(records) {
  const pool = [];
  records.forEach((record, recordIndex) => {
    const [topic, passage, claim, inference, titleDistractor, wrong] = record;
    const targets = [
      claim,
      inference,
      `${topic}에서 조건과 결과 살피기`,
      claim,
    ];
    const stems = [
      "글의 핵심 주장으로 가장 적절한 것은?",
      "본문에서 추론할 수 있는 것은?",
      "글의 제목으로 가장 적절한 것은?",
      "자료를 바탕으로 한 정책 판단은?",
    ];
    for (let variant = 0; variant < 4; variant++) {
      const correct = targets[variant];
      const overreach = `${inference.replace(/다$/, "다는")} 사실만으로 다른 조건에서도 같은 결과가 반드시 보장된다`;
      const distractors = [wrong, titleDistractor, overreach];
      pool.push(
        question(
          `exam-reading-${String(recordIndex * 4 + variant + 1).padStart(2, "0")}`,
          `${passage}\n\n${stems[variant]}`,
          correct,
          distractors,
          `본문은 ${claim}라는 판단을 여러 조건과 자료로 뒷받침한다. 단일 수치나 일부 조건만으로 일반화한 선택지는 배제된다.`,
          ((recordIndex + variant) % 3) + 1,
          variant,
        ),
      );
    }
  });
  return pool;
}

