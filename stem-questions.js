const q = (prompt, options, answer, explanation, difficulty = 1) => {
  let seed = 0;
  for (let i = 0; i < prompt.length; i += 1) {
    seed = (seed + prompt.charCodeAt(i)) % options.length;
  }
  const arrangedOptions = options.map(
    (_, index) => options[(index + seed) % options.length],
  );
  return {
    prompt,
    options: arrangedOptions,
    answer: (answer - seed + options.length) % options.length,
    explanation,
    difficulty,
  };
};

