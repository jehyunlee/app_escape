const finalizePool = (levelId, questions) => {
  const prompts = new Set();
  return questions.map((question, index) => {
    const options = [...question.options];
    if (options.length !== 4 || new Set(options).size !== 4) {
      throw new Error(
        `Stem question ${levelId}-${index + 1} must have four unique options`,
      );
    }
    if (prompts.has(question.prompt)) {
      throw new Error(
        `Duplicate stem prompt in level ${levelId}: ${question.prompt}`,
      );
    }
    prompts.add(question.prompt);
    if (
      !Number.isInteger(question.answer) ||
      question.answer < 0 ||
      question.answer > 3
    ) {
      throw new Error(
        `Stem question ${levelId}-${index + 1} has an invalid answer index`,
      );
    }
    if (![1, 2, 3].includes(question.difficulty)) {
      throw new Error(
        `Stem question ${levelId}-${index + 1} has an invalid difficulty`,
      );
    }
    return {
      id: `stem-${levelId}-${String(index + 1).padStart(3, "0")}`,
      prompt: question.prompt,
      options,
      answer: question.answer,
      explanation: question.explanation,
      difficulty: question.difficulty,
    };
  });
};

